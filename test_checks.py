def _найдено(замечания: list[dict]) -> set[tuple[str, str]]:
    return {(з["проверка"], з["правило"]) for з in замечания}


def проверка_искусственных_правил() -> None:
    with tempfile.TemporaryDirectory() as каталог:
        папка = Path(каталог) / "А_Б"
        папка.mkdir()
        (папка / "ExchangeRules.xml").write_text(ПРАВИЛА, encoding="utf-8")
        (папка / "RegistrationRules.xml").write_text(РЕГИСТРАЦИЯ, encoding="utf-8")
        направление = load_direction(папка)
    assert направление is not None
    замечания = checks.run(направление)
    найдено = _найдено(замечания)

    ждём = {
        ("нет алгоритма", "Док"),  # реквизит «после выгрузки» → НетТакого
        ("нет алгоритма", "НикемНеВызван"),
        ("алгоритм другого режима", "Док"),  # «перед выгрузкой» → алгоритм загрузки
        ("нет правила конвертации", "Док"),  # реквизит → НетПравилаУРеквизита
        ("нет правила конвертации", "Пусковая"),  # код → НетПравила
        ("повтор кода", "Повтор"),
        ("вторая ветка на тот же объект", "Вторая"),  # группа выключена, но БСП её не читает
        ("в ветке не действует", "Пусковая"),
        ("объект не регистрируется", "Пусковая"),  # нет ни правил регистрации, ни в составе плана
        ("объект не регистрируется", "Ручная"),  # в составе плана без авторегистрации
        ("правило не вызывается", "Мёртвое"),  # вызов только закомментированный
        ("правило не вызывается", "ТолькоИзОтключённого"),
        ("правило не вызывается", "БезКлючей"),
        ("правило не вызывается", "ТолькоГруппа"),
        ("правило не вызывается", "МёртвыйПоиск"),
        ("правило не вызывается", "ПродолжениеБезПолей"),
        ("правило не вызывается", "Контрагенты"),
        ("правило не вызывается", "Повтор"),
        ("только ссылкой", "Спр"),
        ("поиск: нет ключей", "БезКлючей"),
        ("поиск: ключ только ЭтоГруппа", "ТолькоГруппа"),  # «Обязательное» = поиск
        ("поиск: обработчик не вызывается", "МёртвыйПоиск"),
        ("поиск: продолжение без полей", "ПродолжениеБезПолей"),
        ("поиск: имя не из полей поиска", "Контрагенты"),
        ("поиск: параметр без признака поиска", "Контрагенты"),
        ("поиск: параметр не передаётся", "Контрагенты"),
        ("запись объекта после загрузки", "Док"),
        ("запись объекта после загрузки", "Конвертация"),
    }
    assert найдено == ждём, f"лишние: {sorted(найдено - ждём)}; потерянные: {sorted(ждём - найдено)}"

    def одно(проверка: str, правило: str) -> dict:
        подходящие = [з for з in замечания if (з["проверка"], з["правило"]) == (проверка, правило)]
        assert len(подходящие) == 1, (проверка, правило, подходящие)
        return подходящие[0]

    # Адрес для чтения: реквизит, обработчик, строка.
    нет = одно("нет алгоритма", "Док")
    assert (нет["код реквизита"], нет["обработчик"], нет["строка"]) == ("2", "ПослеВыгрузки", 1), нет
    assert "НетТакого" in нет["суть"] and нет["уровень"] == checks.ERROR, нет
    # Сломанное в алгоритме, которого никто не зовёт, на обмен не влияет.
    assert одно("нет алгоритма", "НикемНеВызван")["уровень"] == checks.WARNING
    # Из двух причин в ветке — обе, со строками в обработчике.
    ветка = одно("в ветке не действует", "Пусковая")
    assert ветка["строки"] == [1, 2] and "Отказ" in ветка["суть"] and "выборка" in ветка["суть"], ветка
    assert одно("вторая ветка на тот же объект", "Вторая")["суть"].count("Первая") == 1
    assert "вручную" in одно("объект не регистрируется", "Ручная")["суть"]
    assert "ручной выгрузке" in одно("объект не регистрируется", "Пусковая")["суть"]
    # В строке имён — только КПП: ИНН среди полей поиска, сравнение в «Если» и комментарий не в счёт.
    имя = одно("поиск: имя не из полей поиска", "Контрагенты")
    assert "«КПП»" in имя["суть"] and имя["строка"] == 2, имя
    # Спр2 выгружается целиком из реквизита, Спр3 — режимом «при необходимости»: не «только ссылкой».
    assert ("только ссылкой", "Спр2") not in найдено and ("только ссылкой", "Спр3") not in найдено
    print(f"  искусственные правила: {len(замечания)} замечаний, все {len(ждём)} ожидаемых случаев")


def проверка_боевых_правил(root: Path) -> None:
    ix = Index(root)
    упп = ix.directions["УПП_ERP"]
    замечания = checks.run(упп)

    # Опечатка в имени алгоритма: 7 правил ордеров зовут ВыгрузитьХарактеристику,
    # а в правилах есть только ВыгрузитьХарактеристикуНоменклатуры (сверено с файлом).
    нет = [з for з in замечания if з["проверка"] == "нет алгоритма"]
    assert len(нет) == 7, нет
    for з in нет:
        assert "«ВыгрузитьХарактеристику»" in з["суть"] and з["обработчик"] == "ПослеВыгрузки", з
        assert з["реквизит"] == "Характеристика" and з["уровень"] == checks.ERROR, з
    assert "ВыгрузитьХарактеристику" not in упп.algorithms

    # Вторая ветка на документ ABC-классификации не исполняется.
    вторые = [з for з in замечания if з["проверка"] == "вторая ветка на тот же объект"]
    assert [з["правило"] for з in вторые] == ["ВводОстатковТоваров_43"], вторые
    # Первая из них тоже не срабатывает: документа ABC-классификации нет ни в правилах
    # регистрации, ни в составе плана — ветки только для ручной выгрузки остатков.
    без_очереди = {з["правило"] for з in замечания if з["проверка"] == "объект не регистрируется"}
    assert "ВводОстатковТоваров" in без_очереди, без_очереди

    # Вызов только в комментарии и ссылка только из отключённого реквизита — не вызов.
    def не_вызывается(направление: str) -> set[str]:
        return {
            з["правило"]
            for з in checks.run(ix.directions[направление])
            if з["проверка"] == "правило не вызывается"
        }

    assert "КОК_ПеремещениеТоваров" in не_вызывается("УПП_ERP")
    assert {"ОрдерНаОтражениеНедостачТоваров", "Кассы_Ссылка"} <= не_вызывается("Розница_ERP")
    # Явная выгрузка из обработчика реквизита — объект уходит целиком.
    только_ссылкой = {з["правило"] for з in замечания if з["проверка"] == "только ссылкой"}
    assert "ЕдиницыИзмерения_Упаковки_создать" not in только_ссылкой
    assert "Контрагенты_Производители" not in только_ссылкой

    # Каждое замечание с обработчиком указывает на существующий обработчик и строку в нём.
    адресных = 0
    for направление in ix.directions.values():
        for з in checks.run(направление):
            assert set(з) >= {"проверка", "уровень", "вид правила", "правило", "суть", "чем грозит"}, з
            if "обработчик" not in з:
                continue
            вид, код = з["вид правила"], з["правило"]
            if вид == "ПКО":
                пко = направление.pko[код]
                if "код реквизита" in з:
                    место = next(
                        р for р in пко.props + [р for т in пко.sections for р in т.props]
                        if р.code == з["код реквизита"]
                    ).handlers
                elif "код табличной части" in з:
                    место = next(т for т in пко.sections if т.code == з["код табличной части"]).handlers
                else:
                    место = пко.handlers
            elif вид == "ПВД":
                место = next(п for п in направление.pvd if п.code == код).handlers
            elif вид == "Алгоритм":
                место = направление.algorithms[код].handlers
            else:
                место = направление.conversion.handlers
            текст = место[з["обработчик"]]
            for номер in з.get("строки", [з.get("строка", 1)]):
                assert 1 <= номер <= len(текст.splitlines()), з
            адресных += 1
    итог = {н.key: len(checks.run(н)) for н in ix.directions.values()}
    print(f"  боевые правила: {итог}; адресов в коде проверено {адресных}")


