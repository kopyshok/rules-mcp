"""Проверка разбора запросов на реальных правилах.

Запуск:  py -3 test_query_extract.py [каталог_с_направлениями]
По умолчанию берёт ../Data1C. Падает с понятным сообщением, если разбор сломался.
"""

from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

from query_extract import extract_queries
from rules_index import Index

ЭТАЛОН = ("УПП_ERP", "РеализацияТоваровУслуг")

# Дозапись текста запроса — ищется независимо от модуля, чтобы проверка была
# проверкой, а не повторением той же логики. Ловятся и `X.Текст = X.Текст + …`,
# и переписывание себя же: `X.Текст = СтрЗаменить(X.Текст, …)`.
_ДОЗАПИСЬ = re.compile(r"([^\W\d]\w*)\s*\.\s*Текст\s*=(?=.*\b\1\s*\.\s*Текст\b)")


def дозаписи(text: str) -> list[tuple[str, int]]:
    """(переменная, строка) для каждой строки, где текст строится из себя же."""
    out: list[tuple[str, int]] = []
    for номер, строка in enumerate(text.splitlines(), 1):
        if строка.lstrip().startswith("//"):
            continue
        найдено = _ДОЗАПИСЬ.search(строка)
        if найдено is not None:
            out.append((найдено.group(1), номер))
    return out


def все_обработчики(ix: Index):
    """(направление, вид, код правила, имя обработчика, текст) по всему корпусу.

    Кроме правил обходятся общие алгоритмы и именованные запросы: код 1С живёт
    и там, дозаписи текста запроса нашлись именно в алгоритмах.
    """
    for direction in ix.directions.values():
        rules = (
            [("ПВД", rule) for rule in direction.pvd]
            + [("ПКО", rule) for rule in direction.pko.values()]
            + [("ПРО", rule) for rule in direction.pro]
            + [("алгоритм", rule) for rule in direction.algorithms.values()]
            + [("запрос", rule) for rule in direction.queries.values()]
        )
        for kind, rule in rules:
            for name, text in rule.handlers.items():
                yield direction.key, kind, rule.code, name, text


def проверить_литералы() -> None:
    """Многострочный литерал, удвоенные кавычки, комментарии, УНИЧТОЖИТЬ."""
    текст = (
        'Запрос = Новый Запрос;\n'
        'Запрос.Текст =\n'
        '"ВЫБРАТЬ ""Метка;в кавычках"" КАК Метка\n'
        '//|	ЗакомментированнаяКолонка,\n'
        '|ПОМЕСТИТЬ ВТ_Первая\n'
        '|;\n'
        '|ВЫБРАТЬ ВТ_Первая.Метка ИЗ ВТ_Первая КАК ВТ_Первая\n'
        '|ПОМЕСТИТЬ ВТ_Вторая\n'
        '|;\n'
        '|УНИЧТОЖИТЬ ВТ_Первая\n'
        '|;\n'
        '|ВЫБРАТЬ ВТ_Вторая.Метка ИЗ ВТ_Вторая КАК ВТ_Вторая";\n'
        'Запрос.УстановитьПараметр("Дата", Начало(Объект.Дата, "день"));\n'
        'Результат = Запрос.ВыполнитьПакет();\n'
        'Хвост = Результат[3];\n'
        'Кривой = Результат[Всего - 1];\n'
    )
    (использование,) = extract_queries(текст)
    assert использование.complete, использование.reason
    assert использование.assign_line == 2, использование.assign_line
    assert использование.exec_kind == "ВыполнитьПакет"

    # Удвоенная кавычка — одна кавычка, а не конец литерала; `;` внутри не делит пакет.
    assert '"Метка;в кавычках"' in использование.text, использование.text
    # Закомментированная строка внутри литерала в текст не попадает.
    assert "ЗакомментированнаяКолонка" not in использование.text
    # Ведущий `|` снят.
    assert "\n|" not in использование.text, использование.text

    # УНИЧТОЖИТЬ занимает свою позицию: последний запрос остаётся третьим.
    assert [q.temp_table for q in использование.packet] == [
        "ВТ_Первая",
        "ВТ_Вторая",
        "",
        "",
    ], [q.temp_table for q in использование.packet]
    assert использование.packet[1].depends_on == ["ВТ_Первая"]
    assert использование.packet[3].depends_on == ["ВТ_Вторая"]
    assert использование.packet[3].result_vars == ["Хвост"]

    # Вычисляемый номер не угадывается.
    assert [(u.variable, u.expression) for u in использование.unresolved] == [
        ("Кривой", "Всего - 1")
    ]

    # Выражение параметра берётся до закрывающей скобки вызова, со вложенностью.
    (параметр,) = использование.params
    assert параметр.name == "Дата", параметр.name
    assert параметр.expression == 'Начало(Объект.Дата, "день")', параметр.expression

    # Дозапись в цикле: базовый текст выполняется не тот, что записан.
    дозапись = extract_queries(
        'Запрос = Новый Запрос("ВЫБРАТЬ Ссылка ИЗ Справочник.Назначения ГДЕ ИСТИНА");\n'
        "Для Каждого Реквизит Из Реквизиты Цикл\n"
        '	Запрос.Текст = Запрос.Текст + " И " + Реквизит.Имя + " = &Значение";\n'
        "КонецЦикла;\n"
        "Выборка = Запрос.Выполнить().Выбрать();\n"
    )
    assert len(дозапись) == 2, len(дозапись)
    база, приписка = дозапись
    assert not база.complete and база.text is None, "базовый текст выдан за полный"
    assert "3" in база.reason, f"в причине нет строки дозаписи: {база.reason}"
    assert not приписка.complete and приписка.text is None

    # Текст задан переменной — полным его не выдаём.
    (переменной,) = extract_queries('Запрос.Текст = ТекстЗапроса;\nЗапрос.Выполнить();\n')
    assert not переменной.complete and переменной.text is None
    assert переменной.reason, "причина неполноты не заполнена"

    assert extract_queries("") == []
    assert extract_queries("Отказ = Истина;") == []


def проверить_эталон(ix: Index) -> None:
    """УПП_ERP / РеализацияТоваровУслуг — разбираемый случай из спецификации."""
    direction = ix.directions.get(ЭТАЛОН[0])
    if direction is None:
        print(f"направления {ЭТАЛОН[0]} нет — эталонная проверка пропущена")
        return
    pvd = [rule for rule in direction.pvd if rule.code == ЭТАЛОН[1]]
    assert pvd, f"не найдено правило выгрузки {ЭТАЛОН[1]}"
    запросы = {
        name: extract_queries(text)
        for name, text in pvd[0].handlers.items()
        if name in ("ПередОбработкойПравила", "ПередВыгрузкойОбъекта")
    }
    все = [use for uses in запросы.values() for use in uses]

    assert len(все) == 6, f"присваиваний текста {len(все)}, ожидалось 6"
    пакетных = [use for use in все if use.exec_kind == "ВыполнитьПакет"]
    assert len(пакетных) == 3, f"вызовов ВыполнитьПакет {len(пакетных)}, ожидалось 3"
    параметров = sum(len(use.params) for use in все)
    assert параметров == 27, f"параметров {параметров}, ожидалось 27"

    # Номера элементов пакета совпадают с присваиваниями Результат[n].
    выгрузка = запросы["ПередВыгрузкойОбъекта"]
    главный = выгрузка[0]
    assert главный.assign_line == 6 and главный.exec_line == 254
    занятые = sorted(q.index for q in главный.packet if q.result_vars)
    assert занятые == list(range(10)), f"номера с результатами: {занятые}"
    assert len(главный.packet) == 10, f"частей пакета {len(главный.packet)}"
    for use in все:
        for запрос in use.packet:
            assert запрос.index < len(use.packet)

    # Вычисляемый номер на строке 406 не угадан, а помечен.
    вычисляемые = [(u.line, u.variable, u.expression) for use in все for u in use.unresolved]
    assert (406, "РезультатСборка_Шапка", "РезультатСборкаКоличество - 1") in вычисляемые, (
        f"строка 406 не попала в unresolved: {вычисляемые}"
    )

    # Временные таблицы пакетов.
    таблицы = {q.temp_table for use in все for q in use.packet if q.temp_table}
    ожидаемые = {
        "ВТ_Документы",
        "ВТ_Товары",
        "ВТ_ТоварыЛомРТУ",
        "ВТ_ЦеныСерийНоменклатуры",
        "ВТ_ЦеныПервые",
        "ВТ_ЦеныПервыеИтог",
    }
    assert ожидаемые <= таблицы, f"не найдены таблицы: {sorted(ожидаемые - таблицы)}"

    # ВТ_Перемещения и соседи лежат в литералах, которые присвоены обычным
    # переменным и склеиваются в текст запроса через СтрСоединить уже в рантайме.
    # Одно из слагаемых приходит из чужого запроса — текст статически не собрать,
    # поэтому таблицы этой части пакета не видны. Достраивать их догадкой нельзя,
    # но обязан быть честно помеченный неполный запрос, объясняющий пропажу.
    склеенные = {"ВТ_ПеремещенияПредв", "ВТ_Перемещения", "ВТ_Товары_Перемещения"}
    пропали = склеенные - таблицы
    if пропали:
        обработка = запросы["ПередОбработкойПравила"]
        объяснение = [
            use for use in обработка if not use.complete and "СтрСоединить" in use.reason
        ]
        assert объяснение, (
            f"таблицы {sorted(пропали)} не найдены и это никак не помечено — "
            "разбор молча потерял часть пакета"
        )
        print(
            f"  эталон: {len(пропали)} временных таблиц собираются в рантайме "
            f"({', '.join(sorted(пропали))}) — запрос помечен неполным, строка "
            f"{объяснение[0].assign_line}"
        )
    print(f"  эталон: запросов {len(все)}, параметров {параметров}, таблиц {len(таблицы)}")


def проверить_пакет_с_промежуточными(ix: Index) -> None:
    """ВыполнитьПакетСПромежуточнымиДанными размечает результаты так же, как ВыполнитьПакет.

    Порядковые номера в возвращаемом массиве одинаковы, поэтому привязка
    Результат[n] к элементу пакета обязана работать и здесь. Если способ
    выполнения не распознан, такие пакеты молча остаются без разметки.
    """
    живых = 0
    опознано = 0
    размечено = 0
    for направление, вид, код, обработчик, текст in все_обработчики(ix):
        где = f"{направление}/{вид} {код}/{обработчик}"
        строки = [
            n
            for n, line in enumerate(текст.splitlines(), 1)
            if "ВыполнитьПакетСПромежуточнымиДанными" in line
            and not line.strip().startswith("//")
        ]
        живых += len(строки)
        if not строки:
            continue
        for use in extract_queries(текст):
            if use.exec_kind != "ВыполнитьПакетСПромежуточнымиДанными":
                continue
            опознано += 1
            assert use.exec_line in строки, (
                f"{где}: выполнение отмечено строкой {use.exec_line}, "
                f"а вызовы стоят на {строки}"
            )
            размечено += sum(1 for часть in use.packet if часть.result_vars)

    assert живых, "в корпусе не нашлось ни одного вызова — проверка обессмыслилась"
    assert опознано, (
        f"вызовов {живых}, но ни один не опознан: способ выполнения не входит "
        "в перечень распознаваемых, и пакет остаётся без разметки результатов"
    )
    assert размечено, "ни один элемент пакета не получил разметку Результат[n]"
    print(
        f"ВыполнитьПакетСПромежуточнымиДанными: вызовов {живых}, опознано {опознано}, "
        f"элементов с разметкой результата {размечено}"
    )


def main(root: Path) -> int:
    # Консоль Windows по умолчанию не в UTF-8 — иначе падает на кириллице.
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, OSError):
        pass
    assert root.is_dir(), f"нет каталога {root}"

    проверить_литералы()
    print("разбор литералов и пакета: пройдено")

    ix = Index(root)
    assert ix.directions, "не найдено ни одного направления"
    проверить_эталон(ix)
    проверить_пакет_с_промежуточными(ix)

    обработчиков = 0
    запросов = 0
    неполных = 0
    вычисляемых = 0
    частей = 0
    приписок = 0
    причины: Counter[str] = Counter()

    for key, kind, code, name, text in все_обработчики(ix):
        обработчиков += 1
        где = f"{key} / {kind} {code} / {name}"
        try:
            использования = extract_queries(text)
        except Exception as ошибка:  # noqa: BLE001 — модуль не имеет права падать
            raise AssertionError(f"разбор упал на {где}: {ошибка!r}") from ошибка

        запросов += len(использования)

        # К переменной ниже дописывают текст — значит, предыдущее присваивание
        # этой переменной выполняется не в том виде, в каком записано.
        for переменная, строка in дозаписи(text):
            предыдущие = [
                use
                for use in использования
                if use.variable == переменная and use.assign_line < строка
            ]
            if not предыдущие:
                continue
            приписок += 1
            последнее = предыдущие[-1]
            assert not последнее.complete, (
                f"{где}: присваивание на строке {последнее.assign_line} помечено полным, "
                f"хотя на строке {строка} к тексту дописывают"
            )
            assert последнее.text is None, f"{где}: частичный текст на строке {строка}"

        for use in использования:
            частей += len(use.packet)
            вычисляемых += len(use.unresolved)

            # Инвариант: неполный запрос не выдаёт текста.
            if not use.complete:
                неполных += 1
                причины[use.reason] += 1
                assert use.text is None, f"{где}: complete=False, но текст не пуст"
                assert use.reason, f"{где}: complete=False без причины"
                assert not use.packet, f"{где}: complete=False, но пакет разобран"
            else:
                assert use.text is not None, f"{где}: complete=True без текста"
                assert not use.reason, f"{где}: complete=True с причиной «{use.reason}»"

            # Инвариант: зависимости — только таблицы с меньшим номером в пакете.
            созданные: set[str] = set()
            for запрос in use.packet:
                assert запрос.temp_table not in запрос.depends_on, (
                    f"{где}: запрос {запрос.index} зависит сам от себя"
                )
                чужие = [t for t in запрос.depends_on if t not in созданные]
                assert not чужие, (
                    f"{где}: запрос {запрос.index} ссылается на таблицы, "
                    f"созданные позже или вовсе не в пакете: {чужие}"
                )
                if запрос.temp_table:
                    созданные.add(запрос.temp_table)

            assert use.assign_line >= 1
            assert use.exec_line >= 0
            assert (use.exec_kind == "") == (use.exec_line == 0)

    print(f"обработчиков просмотрено: {обработчиков}, исключений нет")
    print(f"QueryUse найдено: {запросов}, запросов в пакетах: {частей}")
    print(f"не извлечено полностью: {неполных}")
    for причина, сколько in причины.most_common():
        print(f"  {сколько:3d}  {причина}")
    print(f"обращений с вычисляемым номером (unresolved): {вычисляемых}")
    print(f"дозаписей текста, обесценивших предыдущее присваивание: {приписок}")
    print("проверка пройдена")
    return 0


if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent / ".." / "Data1C"
    raise SystemExit(main(target.resolve()))
