# Критерий 1: пагинация без потерь


def проверка_пагинация_крупных_обработчиков_без_потерь(ix: Index) -> None:
    крупные = крупные_обработчики(ix)
    assert крупные, (
        f"в данных не нашлось ни одного обработчика длиннее {ПОРОГ_КРУПНОГО} знаков — "
        "проверять пагинацию не на чем"
    )

    for направление, вид, код, имя, текст in крупные:
        где = f"{направление}/{вид} {код}/{имя}"
        страницы = _собрать_страницами(текст, 100, где)

        собрано = "\n".join(
            содержимое for стр in страницы for _, содержимое in
            (_разобрать_строку(ln, где) for ln in (стр["текст"].splitlines() if стр["текст"] else []))
        )
        assert собрано == текст, (
            f"{где}: сборка страниц не совпала с исходным текстом. "
            f"Исходник {len(текст)} знаков, собрано {len(собрано)}; "
            f"первое расхождение на позиции {_первое_расхождение(текст, собрано)}"
        )

    print(f"  крупных обработчиков (>{ПОРОГ_КРУПНОГО} знаков): {len(крупные)} — все собрались знак в знак")


def _первое_расхождение(a: str, b: str) -> str:
    предел = min(len(a), len(b))
    for i in range(предел):
        if a[i] != b[i]:
            return f"{i}: было {a[i - 40:i + 40]!r}, стало {b[i - 40:i + 40]!r}"
    if len(a) == len(b):
        return "нет"
    хвост = (a if len(a) > len(b) else b)[предел:предел + 80]
    сторона = "исходнике" if len(a) > len(b) else "сборке"
    return f"{предел}: лишний хвост в {сторона}: {хвост!r}"


