# Критерий 2: непрерывность страниц


def проверка_непрерывность_страниц(ix: Index) -> None:
    крупные = крупные_обработчики(ix)
    # Разные шаги, чтобы поймать краевые случаи «ровно делится» и «не делится».
    шаги = (1, 7, 100, 500)
    проверено = 0
    for направление, вид, код, имя, текст in крупные[:5]:
        всего = len(текст.splitlines())
        for шаг in шаги:
            где = f"{направление}/{вид} {код}/{имя}, шаг {шаг}"
            if шаг == 1 and всего > 400:
                continue  # шаг 1 гоняем только на коротком, иначе это тысячи вызовов
            страницы = _собрать_страницами(текст, шаг, где)

            for стр in страницы:
                assert стр["всего строк"] == всего, (
                    f"{где}: 'всего строк' = {стр['всего строк']}, а в тексте строк {всего}"
                )
            for предыдущая, следующая in zip(страницы, страницы[1:]):
                assert предыдущая["следующая строка"] == следующая["с строки"], (
                    f"{где}: страница кончилась на 'следующая строка' = "
                    f"{предыдущая['следующая строка']}, а следующая началась "
                    f"с {следующая['с строки']} — пропуск или нахлёст"
                )
            сумма = sum(стр["показано строк"] for стр in страницы)
            assert сумма == всего, (
                f"{где}: сумма 'показано строк' по страницам = {сумма}, "
                f"а строк в обработчике {всего}"
            )
            assert страницы[-1]["по строку"] == всего, (
                f"{где}: последняя страница кончается на {страницы[-1]['по строку']}, "
                f"а строк {всего}"
            )
            проверено += 1
    print(f"  непрерывность: проверено {проверено} проходов по страницам")


