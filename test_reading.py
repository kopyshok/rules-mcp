"""Приёмочные проверки чтения правил: page_lines, Index.find_rule, Index.search.

Написаны до реализации (TDD) по спецификации TZ/spec-rules-mcp-v2.md,
разделы 1.2, 1.5, 2, 3.2 и критерии приёмки 1-6 раздела 7.

Ожидаемые значения считаются прямо из боевых данных Data1C, а не через
проверяемые функции — иначе проверка выродилась бы в сверку реализации
с самой собой.

Запуск:  py -3 test_reading.py [каталог_с_направлениями]
По умолчанию берёт ../Data1C.

Пока проверяемых функций нет, файл обязан падать с AttributeError на
rules_index.page_lines / Index.find_rule / Index.search — это ожидаемое
состояние, а не поломка теста.
"""

from __future__ import annotations

import copy
import dataclasses
import re
import sys
from pathlib import Path

import rules_index
from rules_index import Direction, Index, obj_short

# Формат строки текста из 1.2: "%5d | %s". Разбираем его обратно, чтобы
# собирать страницы в исходный текст и сверять номера.
_НОМЕР_СТРОКИ = re.compile(r"^ *(\d+) \| ")

# Опорная точка всех проверок: самый разобранный в спецификации обработчик.
НАПРАВЛЕНИЕ = "УПП_ERP"
ПРАВИЛО = "РеализацияТоваровУслуг"
ОБРАБОТЧИК = "ПередВыгрузкойОбъекта"

# Номера строк, названные в спецификации (раздел 3.2 и п. 5 критериев приёмки).
# Тест им не верит на слово: сверяет с данными и печатает расхождение.
СПЕЦ_СТРОКА_ВЫЗОВА = 430
СПЕЦ_СТРОКА_КОММЕНТАРИЯ = 812
СПЕЦ_СТРОКА_ЖИВОГО_ВЫЗОВА = 819

ПОРОГ_КРУПНОГО = 20_000  # знаков; по спецификации таких обработчиков около 41

# Порядок обхода видов в search зафиксирован спецификацией (1.4.1). Он не совпадает
# с порядком перечисления в RULE_KINDS, поэтому задан отдельно.
ПОРЯДОК_ОБХОДА = ("ПКО", "ПВД", "ПРО", "Алгоритм", "Запрос")


