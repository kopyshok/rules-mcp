# Вспомогательные выборки из данных (без участия проверяемых функций)


def коллекции(направление: Direction) -> tuple[tuple[str, list], ...]:
    """Все пять видов кода направления: три вида правил, алгоритмы и запросы (1.4.1)."""
    return (
        ("ПВД", list(направление.pvd)),
        ("ПКО", list(направление.pko.values())),
        ("ПРО", list(направление.pro)),
        ("Алгоритм", list(направление.algorithms.values())),
        ("Запрос", list(направление.queries.values())),
    )


def все_обработчики(ix: Index) -> list[tuple[str, str, str, str, str]]:
    """Плоский список (направление, вид, код, обработчик, текст)."""
    out: list[tuple[str, str, str, str, str]] = []
    for направление in ix.directions.values():
        for вид, правила in коллекции(направление):
            for правило in правила:
                for имя, текст in правило.handlers.items():
                    out.append((направление.key, вид, правило.code, имя, текст))
    return out


def обработчики_реквизитов(ix: Index) -> dict[tuple[str, str, str], tuple[str, object]]:
    """(направление, код ПКО, код реквизита) → (табличная часть, реквизит).

    Только реквизиты с обработчиком. Собрано прямо из полей правила, без
    rules_index.all_props — иначе проверка сверяла бы реализацию с ней самой.
    """
    out: dict[tuple[str, str, str], tuple[str, object]] = {}
    for направление in ix.directions.values():
        for пко in направление.pko.values():
            группы = [("", пко.props)] + [(т.dst or т.name, т.props) for т in пко.sections]
            for раздел, реквизиты in группы:
                for р in реквизиты:
                    if р.handler:
                        out[(направление.key, пко.code, р.code)] = (раздел, р)
    return out


def текст_попадания(hit: dict, тексты: dict, реквизиты: dict) -> tuple[tuple, str]:
    """Ключ и текст, куда попал поиск: обработчик правила или обработчик реквизита.

    У обоих обработчик может зваться ПередВыгрузкой, различает их только код реквизита.
    """
    if "код реквизита" in hit:
        ключ = (hit["направление"], hit["правило"], hit["код реквизита"])
        assert ключ in реквизиты, f"поиск вернул реквизит, которого нет в индексе: {ключ}"
        return ключ, реквизиты[ключ][1].handler
    ключ = (hit["направление"], hit["вид правила"], hit["правило"], hit["обработчик"])
    assert ключ in тексты, f"поиск вернул обработчик, которого нет в индексе: {ключ}"
    return ключ, тексты[ключ]


def крупные_обработчики(ix: Index) -> list[tuple[str, str, str, str, str]]:
    """Обработчики длиннее ПОРОГ_КРУПНОГО знаков — те, ради которых нужна пагинация."""
    return [item for item in все_обработчики(ix) if len(item[4]) > ПОРОГ_КРУПНОГО]


def опорный_текст(ix: Index) -> str:
    """Текст УПП_ERP / ПВД РеализацияТоваровУслуг / ПередВыгрузкойОбъекта."""
    направление = ix.directions[НАПРАВЛЕНИЕ]
    подходящие = [p for p in направление.pvd if p.code == ПРАВИЛО]
    assert подходящие, f"в {НАПРАВЛЕНИЕ} нет ПВД с кодом {ПРАВИЛО}"
    handlers = подходящие[0].handlers
    assert ОБРАБОТЧИК in handlers, (
        f"у ПВД {ПРАВИЛО} нет обработчика {ОБРАБОТЧИК}, есть: {sorted(handlers)}"
    )
    return handlers[ОБРАБОТЧИК]


def строки_с(текст: str, игла: str, закомментированные: bool) -> list[int]:
    """Номера строк (от 1), где встречается игла.

    закомментированные=False — только живые строки, как их считает поиск (3.5).
    """
    найдено = []
    for номер, строка in enumerate(текст.splitlines(), 1):
        обрезанная = строка.strip()
        if игла.casefold() not in обрезанная.casefold():
            continue
        if обрезанная.startswith("//") != закомментированные:
            continue
        найдено.append(номер)
    return найдено


def _разобрать_строку(строка: str, где: str) -> tuple[int, str]:
    """"  430 | Код" → (430, "Код"). Формат задан в 1.2 как "%5d | %s"."""
    совпадение = _НОМЕР_СТРОКИ.match(строка)
    assert совпадение, (
        f"{где}: строка не в формате '%5d | %s': {строка!r}"
    )
    return int(совпадение.group(1)), строка[совпадение.end():]


def _проверить_поля_страницы(стр: dict, где: str) -> list[tuple[int, str]]:
    """Инварианты 1.2, общие для любой страницы. Возвращает разобранные строки."""
    обязательные = {"всего строк", "с строки", "по строку", "показано строк", "обрезано", "текст"}
    отсутствуют = обязательные - set(стр)
    assert not отсутствуют, f"{где}: в ответе нет полей {sorted(отсутствуют)}, есть {sorted(стр)}"

    текст = стр["текст"]
    разобранные = [
        _разобрать_строку(ln, где) for ln in (текст.splitlines() if текст else [])
    ]

    assert стр["показано строк"] == len(разобранные), (
        f"{где}: 'показано строк' = {стр['показано строк']}, "
        f"а в поле 'текст' строк {len(разобранные)}"
    )
    assert isinstance(стр["обрезано"], bool), (
        f"{где}: 'обрезано' должно быть булевым, пришло {стр['обрезано']!r}"
    )

    if разобранные:
        номера = [n for n, _ in разобранные]
        assert номера[0] == стр["с строки"], (
            f"{где}: 'с строки' = {стр['с строки']}, а первая строка текста имеет номер {номера[0]}"
        )
        assert номера[-1] == стр["по строку"], (
            f"{где}: 'по строку' = {стр['по строку']}, а последняя строка текста "
            f"имеет номер {номера[-1]}"
        )
        ожидаемые = list(range(номера[0], номера[0] + len(номера)))
        assert номера == ожидаемые, (
            f"{где}: номера строк идут не подряд: {номера[:5]}… ожидалось {ожидаемые[:5]}…"
        )

    if стр["обрезано"]:
        assert "следующая строка" in стр, (
            f"{где}: 'обрезано' = true, но поля 'следующая строка' нет (1.2)"
        )
        assert стр["следующая строка"] == стр["по строку"] + 1, (
            f"{где}: 'следующая строка' = {стр['следующая строка']}, "
            f"ожидалось 'по строку' + 1 = {стр['по строку'] + 1}"
        )
        assert стр["следующая строка"] <= стр["всего строк"], (
            f"{где}: 'следующая строка' = {стр['следующая строка']} "
            f"выходит за 'всего строк' = {стр['всего строк']} — обрезать было нечего"
        )
    else:
        assert стр.get("следующая строка") is None, (
            f"{где}: текст не обрезан, но есть 'следующая строка' = {стр['следующая строка']} (1.2)"
        )
        assert стр["по строку"] == стр["всего строк"] or стр["всего строк"] == 0, (
            f"{где}: 'обрезано' = false, но прочитано по строку {стр['по строку']} "
            f"из {стр['всего строк']}"
        )
    return разобранные


def _собрать_страницами(текст: str, шаг: int, где: str) -> list[dict]:
    """Идёт по 'следующая строка' от начала до конца. Возвращает все страницы."""
    всего = len(текст.splitlines())
    страницы: list[dict] = []
    начало = 1
    # Предохранитель от зацикливания: страниц не может быть больше, чем строк.
    предел = всего + 2
    while True:
        стр = rules_index.page_lines(текст, start_line=начало, max_lines=шаг)
        _проверить_поля_страницы(стр, f"{где}, страница с {начало}")
        страницы.append(стр)
        assert len(страницы) <= предел, (
            f"{где}: чтение не заканчивается, уже {len(страницы)} страниц при {всего} строках"
        )
        if not стр["обрезано"]:
            return страницы
        начало = стр["следующая строка"]


