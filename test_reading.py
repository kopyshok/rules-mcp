def проверка_search_фильтры_сужают_выдачу(ix: Index) -> None:
    направление = ix.directions[НАПРАВЛЕНИЕ]
    запрос = ШИРОКИЙ_ЗАПРОС
    БОЛЬШОЙ = 10_000

    база = ix.search([направление], запрос, limit=БОЛЬШОЙ, lines_per_handler=5)
    assert len(база) > 20, (
        f"поиск {запрос} в {НАПРАВЛЕНИЕ} дал всего {len(база)} попаданий — "
        "для проверки фильтров нужна выдача пошире"
    )
    виды_в_базе = {h["вид правила"] for h in база}
    assert виды_в_базе == set(rules_index.RULE_KINDS), (
        f"запрос {запрос} попал только в {sorted(виды_в_базе)} — "
        f"фильтр по виду правила нечего будет сужать, нужен запрос пошире"
    )

    def отфильтровать(**фильтры) -> list[dict]:
        return ix.search([направление], запрос, limit=БОЛЬШОЙ, lines_per_handler=5, **фильтры)

    def самое_частое(поле: str) -> str:
        счёт: dict[str, int] = {}
        for h in база:
            if поле in h:
                счёт[h[поле]] = счёт.get(h[поле], 0) + 1
        return max(счёт, key=lambda k: (счёт[k], k))

    частое_правило = самое_частое("правило")
    частый_обработчик = самое_частое("обработчик")
    наборы = [
        *(
            ("kind", вид, (lambda в: lambda h: h["вид правила"] == в)(вид))
            for вид in rules_index.RULE_KINDS
        ),
        ("rule", частое_правило, lambda h: h["правило"] == частое_правило),
        ("handler", частый_обработчик, lambda h: h.get("обработчик") == частый_обработчик),
    ]
    for имя, значение, подходит in наборы:
        выдача = отфильтровать(**{имя: значение})
        assert выдача, f"фильтр {имя}={значение} обнулил выдачу по запросу {запрос}"
        нарушители = [_ключ(h) for h in выдача if not подходит(h)]
        assert not нарушители, (
            f"фильтр {имя}={значение} пропустил чужие попадания: {нарушители[:5]}"
        )
        ожидалось = {_ключ(h) for h in база if подходит(h)}
        получено = {_ключ(h) for h in выдача}
        assert получено == ожидалось, (
            f"фильтр {имя}={значение}: лишние {sorted(получено - ожидалось)[:5]}, "
            f"потерянные {sorted(ожидалось - получено)[:5]}"
        )
        assert len(выдача) <= len(база), (
            f"фильтр {имя}={значение} дал {len(выдача)} попаданий против {len(база)} без фильтра"
        )

    # Фильтры складываются по «и» (3.1).
    вместе = отфильтровать(kind="ПВД", rule=ПРАВИЛО, handler=ОБРАБОТЧИК)
    ожидалось = {
        _ключ(h) for h in база
        if h["вид правила"] == "ПВД"
        and h["правило"] == ПРАВИЛО
        and h.get("обработчик") == ОБРАБОТЧИК
    }
    assert ожидалось, (
        f"запрос {запрос} не попал в {ПРАВИЛО}/{ОБРАБОТЧИК} — совмещённые фильтры "
        "нечего проверять"
    )
    assert {_ключ(h) for h in вместе} == ожидалось, (
        f"совмещённые фильтры дали {len(вместе)} попаданий, ожидалось {len(ожидалось)}"
    )

    # Несуществующее правило в отборе — ошибка, а не пустая выдача (2.1.0):
    # опечатка не должна выглядеть как «ничего не нашлось».
    сообщение = _ошибка(lambda: отфильтровать(rule="ТакогоПравилаНетИНеБудет_20260918"))
    assert сообщение and "ТакогоПравилаНетИНеБудет_20260918" in сообщение, (
        f"фильтр по несуществующему правилу не дал внятной ошибки: {сообщение!r}"
    )

    # limit соблюдается.
    for предел in (1, 3, 10):
        урезанная = ix.search([направление], запрос, limit=предел, lines_per_handler=5)
        assert len(урезанная) <= предел, (
            f"limit = {предел}, а поиск вернул {len(урезанная)} попаданий"
        )
        assert len(урезанная) == min(предел, len(база)), (
            f"limit = {предел}: вернулось {len(урезанная)}, ожидалось "
            f"{min(предел, len(база))} — выдача урезана раньше времени"
        )

    # lines_per_handler ограничивает число строк на один обработчик.
    for на_обработчик in (1, 2):
        выдача = ix.search(
            [направление], запрос, limit=БОЛЬШОЙ, lines_per_handler=на_обработчик
        )
        счёт: dict[tuple, int] = {}
        for h in выдача:
            if "обработчик" not in h:
                continue  # попадание по соответствию реквизитов, строк не имеет
            ключ = (h["направление"], h["вид правила"], h["правило"], h["обработчик"],
                     h.get("код реквизита"))
            счёт[ключ] = счёт.get(ключ, 0) + 1
        перебор = {k: v for k, v in счёт.items() if v > на_обработчик}
        assert not перебор, (
            f"lines_per_handler = {на_обработчик}, а строк на обработчик больше: "
            f"{list(перебор.items())[:3]}"
        )
    print(f"  search: база {len(база)} попаданий, фильтры и limit соблюдены")


def проверка_search_порядок_обхода_и_неизвестный_вид(ix: Index) -> None:
    направление = ix.directions[НАПРАВЛЕНИЕ]

    # Порядок обхода видов зафиксирован: ПКО, ПВД, ПРО, Алгоритм, Запрос (1.4.1).
    порядок = ПОРЯДОК_ОБХОДА
    assert set(порядок) == set(rules_index.RULE_KINDS), (
        f"порядок обхода {порядок} не покрывает RULE_KINDS = {rules_index.RULE_KINDS}"
    )
