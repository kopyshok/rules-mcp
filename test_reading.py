# Критерий 3: согласованность номеров строк


def проверка_номера_строк_совпадают_с_текстом(ix: Index) -> None:
    текст = опорный_текст(ix)
    строки = текст.splitlines()
    всего = len(строки)

    интересные = sorted({1, 2, всего // 2, всего - 1, всего, СПЕЦ_СТРОКА_ВЫЗОВА})
    for номер in интересные:
        if not 1 <= номер <= всего:
            continue
        стр = rules_index.page_lines(текст, start_line=номер, max_lines=1)
        _проверить_поля_страницы(стр, f"{ПРАВИЛО}/{ОБРАБОТЧИК}, строка {номер}")
        assert стр["всего строк"] == всего, (
            f"строка {номер}: 'всего строк' = {стр['всего строк']}, а в тексте {всего}"
        )
        прочитанный_номер, содержимое = _разобрать_строку(
            стр["текст"], f"{ПРАВИЛО}/{ОБРАБОТЧИК}, строка {номер}"
        )
        assert прочитанный_номер == номер, (
            f"просили строку {номер}, вернулась строка с номером {прочитанный_номер}"
        )
        assert содержимое == строки[номер - 1], (
            f"строка {номер}: вернулось {содержимое!r}, "
            f"а в тексте обработчика {строки[номер - 1]!r}"
        )

    # Явная сверка со спецификацией: строка 430 — вызов ПКО ПеремещениеТоваров.
    вызов = строки[СПЕЦ_СТРОКА_ВЫЗОВА - 1]
    assert "ВыгрузитьПоПравилу" in вызов and "РеализацияТоваровУслуг_ПеремещениеТоваров" in вызов, (
        f"спецификация обещает вызов ПеремещениеТоваров на строке {СПЕЦ_СТРОКА_ВЫЗОВА}, "
        f"а там {вызов!r} — данные разошлись со спецификацией"
    )
    print(f"  номера строк: проверено {len(интересные)} точек в {ПРАВИЛО}/{ОБРАБОТЧИК}")


def проверка_номер_из_поиска_годится_для_чтения(ix: Index) -> None:
    направление = ix.directions[НАПРАВЛЕНИЕ]
    попадания = ix.search([направление], ШИРОКИЙ_ЗАПРОС, limit=10_000, lines_per_handler=5)
    assert попадания, f"поиск {ШИРОКИЙ_ЗАПРОС} в {НАПРАВЛЕНИЕ} не дал ни одного попадания"
    assert {h["вид правила"] for h in попадания} == set(rules_index.RULE_KINDS), (
        f"запрос {ШИРОКИЙ_ЗАПРОС} попал только в "
        f"{sorted({h['вид правила'] for h in попадания})} — номера строк проверяются "
        "не у всех видов правил"
    )

    тексты = {
        (напр, вид, код, имя): текст
        for напр, вид, код, имя, текст in все_обработчики(ix)
    }
    реквизиты = обработчики_реквизитов(ix)
    с_номером = 0
    for hit in попадания:
        if "строка" not in hit:
            continue  # попадания по соответствиям реквизитов номера не имеют (3.2)
        ключ, текст = текст_попадания(hit, тексты, реквизиты)
        номер = hit["строка"]
        стр = rules_index.page_lines(текст, start_line=номер, max_lines=1)
        _, содержимое = _разобрать_строку(стр["текст"], f"поиск {ключ}, строка {номер}")
        assert содержимое == текст.splitlines()[номер - 1], (
            f"{ключ}: page_lines на строке {номер} отдал {содержимое!r}, "
            f"а в тексте {текст.splitlines()[номер - 1]!r}"
        )
        обрезан = bool(hit.get("фрагмент обрезан"))
        ожидаемый_фрагмент = содержимое.strip()[:200] if обрезан else содержимое.strip()
        assert hit["фрагмент"] == ожидаемый_фрагмент, (
            f"{ключ}, строка {номер}: 'фрагмент' = {hit['фрагмент']!r}, "
            f"а строка в тексте {ожидаемый_фрагмент!r}"
        )
        if обрезан:
            assert len(содержимое.strip()) > 200, (
                f"{ключ}, строка {номер}: помечено 'фрагмент обрезан', "
                f"но строка длиной {len(содержимое.strip())} знаков — резать нечего (3.2)"
            )
        с_номером += 1
    assert с_номером, "ни одно попадание поиска не несёт номера строки"
    print(f"  номера из поиска: проверено {с_номером} попаданий, все читаются page_lines")


