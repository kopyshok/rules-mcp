# Запрос для проверки фильтров: обязан попадать во все три вида правил, иначе
# фильтр по виду ничего не сузит и проверка выродится в тавтологию.
ШИРОКИЙ_ЗАПРОС = "Возврат"


def _ключ(hit: dict) -> tuple:
    # Попадания по соответствиям реквизитов обработчика и номера строки не имеют (3.2).
    return (
        hit["направление"],
        hit["вид правила"],
        hit["правило"],
        hit.get("обработчик"),
        hit.get("строка"),
        hit.get("что"),
        hit.get("код реквизита"),
    )


