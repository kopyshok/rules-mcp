def проверка_алгоритмы_и_запросы_читаются(ix: Index) -> None:
    направление = ix.directions[НАПРАВЛЕНИЕ]
    assert направление.algorithms, f"в {НАПРАВЛЕНИЕ} не прочитано ни одного общего алгоритма"
    assert направление.queries, f"в {НАПРАВЛЕНИЕ} не прочитано ни одного именованного запроса"

    for вид, склад in (("Алгоритм", направление.algorithms), ("Запрос", направление.queries)):
        # Обработчик у сниппета ровно один и называется «Текст» (1.4.1).
        assert rules_index.HANDLER_NAMES[вид] == ("Текст",), (
            f"HANDLER_NAMES[{вид!r}] = {rules_index.HANDLER_NAMES[вид]}, ожидалось ('Текст',)"
        )
        for сниппет in склад.values():
            assert list(сниппет.handlers) == ["Текст"], (
                f"{вид} {сниппет.code}: обработчики {list(сниппет.handlers)}, "
                "ожидался единственный «Текст»"
            )

        # Самый большой из них читается страницами и собирается знак в знак.
        крупнейший = max(склад.values(), key=lambda s: len(s.handlers["Текст"]))
        текст = крупнейший.handlers["Текст"]
        где = f"{НАПРАВЛЕНИЕ}/{вид} {крупнейший.code}"
        страницы = _собрать_страницами(текст, 100, где)
        собрано = "\n".join(
            содержимое
            for стр in страницы
            for _, содержимое in (
                _разобрать_строку(ln, где) for ln in (стр["текст"].splitlines() if стр["текст"] else [])
            )
        )
        assert собрано == текст, (
            f"{где}: сборка страниц разошлась с исходником, "
            f"{_первое_расхождение(текст, собрано)}"
        )

        # Через handler_text — тем же путём, что и правила.
        имя, через_функцию = rules_index.handler_text(крупнейший, вид, "текст")
        assert (имя, через_функцию) == ("Текст", текст), (
            f"{где}: handler_text('текст') вернул имя {имя!r} и {len(через_функцию)} знаков, "
            f"ожидалось 'Текст' и {len(текст)}"
        )

        # find_rule находит их по имени, как правила.
        найденный_вид, найденный = ix.find_rule(направление, крупнейший.code)
        assert (найденный_вид, найденный.code) == (вид, крупнейший.code), (
            f"find_rule({крупнейший.code!r}) вернул {найденный_вид} {найденный.code!r}, "
            f"ожидался {вид}"
        )
        вид_2, найденный_2 = ix.find_rule(направление, крупнейший.code.upper(), вид)
        assert (вид_2, найденный_2.code) == (вид, крупнейший.code), (
            f"{вид} {крупнейший.code}: регистр имени повлиял на find_rule"
        )

    # Главное, ради чего алгоритмы вообще читаются: вызов ПКО, спрятанный в
    # алгоритме и невидимый в самих ветках выгрузки, обязан находиться поиском.
    из_алгоритмов: set[str] = set()
    for алгоритм in направление.algorithms.values():
        из_алгоритмов.update(алгоритм.pko_calls)
    из_веток: set[str] = set()
    for пвд in направление.pvd:
        из_веток.update(пвд.pko_calls)
    только_в_алгоритмах = sorted(из_алгоритмов - из_веток)
    assert только_в_алгоритмах, (
        f"в {НАПРАВЛЕНИЕ} нет ПКО, вызываемых только из алгоритмов — "
        "проверять скрытые вызовы не на чем"
    )

    for имя_пко in только_в_алгоритмах[:5]:
        попадания = ix.search([направление], имя_пко, limit=100, lines_per_handler=10)
        в_алгоритмах = [h for h in попадания if h["вид правила"] == "Алгоритм"]
        assert в_алгоритмах, (
            f"ПКО {имя_пко} вызывается только из алгоритмов, а поиск не нашёл вызова там; "
            f"вернулось {[(h['вид правила'], h['правило']) for h in попадания]}"
        )
        for h in в_алгоритмах:
            сниппет = направление.algorithms[h["правило"]]
            строка = сниппет.handlers["Текст"].splitlines()[h["строка"] - 1]
            assert имя_пко.casefold() in строка.casefold(), (
                f"поиск {имя_пко} указал на {h['правило']} строку {h['строка']}, "
                f"а там {строка.strip()[:80]!r}"
            )
        assert not [h for h in попадания if h["вид правила"] == "ПВД"], (
            f"ПКО {имя_пко} не значится в вызовах ни одной ветки, а поиск нашёл его в ПВД: "
            f"{[(h['правило'], h['обработчик'], h['строка']) for h in попадания if h['вид правила'] == 'ПВД']}"
        )

    print(
        f"  алгоритмы и запросы: {len(направление.algorithms)} алгоритмов, "
        f"{len(направление.queries)} запросов, ПКО только из алгоритмов — "
        f"{len(только_в_алгоритмах)}"
    )


def проверка_algorithms_used(ix: Index) -> None:
    направление = ix.directions[НАПРАВЛЕНИЕ]

    # Вызовы, найденные по тексту, обязаны совпадать с pko_calls самих алгоритмов.
    ветки_со_скрытыми = 0
    for напр in ix.directions.values():
        for пвд in напр.pvd:
            текст = "\n".join(пвд.handlers.values())
            использованы = ix.algorithms_used(напр, текст)
            for имя, вызовы in использованы.items():
                assert имя in напр.algorithms, (
                    f"{напр.key}/{пвд.code}: algorithms_used назвал алгоритм {имя!r}, "
                    f"которого нет в направлении"
                )
                assert вызовы == напр.algorithms[имя].pko_calls, (
                    f"{напр.key}: у алгоритма {имя} вызовы {вызовы}, "
                    f"а в индексе {напр.algorithms[имя].pko_calls}"
                )
            спрятанные: set[str] = set()
            for вызовы in использованы.values():
                спрятанные.update(вызовы)
            if спрятанные - set(пвд.pko_calls):
                ветки_со_скрытыми += 1
    assert ветки_со_скрытыми, (
        "ни у одной ветки корпуса через алгоритмы не достигается ПКО, "
        "не видный в самой ветке — ради чего тогда обход алгоритмов"
    )

    # Закомментированный вызов алгоритма не считается.
    живой = next(iter(направление.algorithms))
    assert ix.algorithms_used(направление, f"Выполнить(Алгоритмы.{живой});"), (
        f"вызов алгоритма {живой} по тексту не распознан"
    )
    закомментировано = ix.algorithms_used(направление, f"//Выполнить(Алгоритмы.{живой});")
    assert закомментировано == {}, (
        f"закомментированный вызов алгоритма {живой} учтён: {закомментировано}"
    )

    # Неизвестное имя алгоритма молча пропускается, а не роняет обход.
    assert ix.algorithms_used(направление, "Выполнить(Алгоритмы.ТакогоАлгоритмаНет_20260918);") == {}, (
        "вызов несуществующего алгоритма не должен ничего добавлять в выдачу"
    )

    # Рекурсия не зацикливается. В данных самозовущихся алгоритмов нет
    # (проверяется тут же), поэтому случай собирается искусственно.
    самозовущиеся = [
        с.code for с in направление.algorithms.values()
        if с.code in rules_index._ALG_CALL_RE.findall(
            rules_index._uncommented(с.handlers["Текст"])
        )
    ]
    assert not самозовущиеся, (
        f"в данных появились самозовущиеся алгоритмы {самозовущиеся[:3]} — "
        "искусственный случай ниже можно заменить на боевой"
    )

    клон = copy.copy(направление)
    клон.algorithms = dict(направление.algorithms)
    образец = next(iter(направление.algorithms.values()))
    клон.algorithms["СамЗоветСебя"] = dataclasses.replace(
        образец,
        code="СамЗоветСебя",
        name="СамЗоветСебя",
        handlers={"Текст": 'Выполнить(Алгоритмы.СамЗоветСебя);\nВыгрузитьПоПравилу(О,,,, "ПКО_А",,,,,);'},
        pko_calls=["ПКО_А"],
    )
    клон.algorithms["Пинг"] = dataclasses.replace(
        образец,
        code="Пинг",
        name="Пинг",
        handlers={"Текст": 'Выполнить(Алгоритмы.Понг);\nВыгрузитьПоПравилу(О,,,, "ПКО_Б",,,,,);'},
        pko_calls=["ПКО_Б"],
    )
    клон.algorithms["Понг"] = dataclasses.replace(
        образец,
        code="Понг",
        name="Понг",
        handlers={"Текст": 'Выполнить(Алгоритмы.Пинг);\nВыгрузитьПоПравилу(О,,,, "ПКО_В",,,,,);'},
        pko_calls=["ПКО_В"],
    )

    сам = ix.algorithms_used(клон, "Выполнить(Алгоритмы.СамЗоветСебя);")
    assert сам == {"СамЗоветСебя": ["ПКО_А"]}, (
        f"алгоритм, зовущий сам себя, разобрался как {сам} — ожидалось "
        "{'СамЗоветСебя': ['ПКО_А']} без зацикливания"
    )
    кольцо = ix.algorithms_used(клон, "Выполнить(Алгоритмы.Пинг);")
    assert кольцо == {"Пинг": ["ПКО_Б"], "Понг": ["ПКО_В"]}, (
        f"взаимный вызов двух алгоритмов разобрался как {кольцо} — ожидались оба, по разу"
    )

    print(f"  algorithms_used: веток со скрытыми через алгоритмы ПКО по корпусу — {ветки_со_скрытыми}")


