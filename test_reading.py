def проверка_handler_names_порядок_выполнения(ix: Index) -> None:
    # По всему корпусу: состав не теряется и не прирастает, порядок — по HANDLER_NAMES.
    проверено = 0
    for направление in ix.directions.values():
        for вид, правила in коллекции(направление):
            порядок = rules_index.HANDLER_NAMES[вид]
            for правило in правила:
                if not правило.handlers:
                    continue
                где = f"{направление.key}/{вид} {правило.code}"
                имена = rules_index.handler_names(вид, правило.handlers)
                assert sorted(имена) == sorted(правило.handlers), (
                    f"{где}: handler_names вернул {имена}, "
                    f"а у правила обработчики {sorted(правило.handlers)}"
                )
                assert len(имена) == len(set(имена)), (
                    f"{где}: handler_names повторил имена: {имена}"
                )
                известные = [n for n in имена if n in порядок]
                эталон = [n for n in порядок if n in правило.handlers]
                assert известные == эталон, (
                    f"{где}: порядок обработчиков {известные}, "
                    f"а по HANDLER_NAMES ожидался {эталон}"
                )
                неизвестные = [n for n in имена if n not in порядок]
                if неизвестные:
                    assert имена[len(известные):] == неизвестные, (
                        f"{где}: имена вне HANDLER_NAMES должны идти в конце, пришло {имена}"
                    )
                проверено += 1

    # Словарь не задаёт порядок: подсовываем перевёрнутый — результат тот же.
    направление = ix.directions[НАПРАВЛЕНИЕ]
    пвд = [p for p in направление.pvd if p.code == ПРАВИЛО][0]
    ожидаемый = [
        "ПередОбработкойПравила",
        "ПередВыгрузкойОбъекта",
        "ПослеВыгрузкиОбъекта",
        "ПослеОбработкиПравила",
    ]
    assert sorted(пвд.handlers) == sorted(ожидаемый), (
        f"у ПВД {ПРАВИЛО} обработчики {sorted(пвд.handlers)}, ожидались {sorted(ожидаемый)}"
    )
    перевёрнутый = dict(reversed(list(пвд.handlers.items())))
    имена = rules_index.handler_names("ПВД", перевёрнутый)
    assert имена == ожидаемый, (
        f"из перевёрнутого словаря handler_names вернул {имена}, "
        f"а порядок выполнения {ожидаемый} — сортировки по HANDLER_NAMES не произошло"
    )

    # Имена вне HANDLER_NAMES в данных не встречаются (разбор берёт только известные),
    # поэтому проверяем их на искусственном словаре: они обязаны уцелеть в конце.
    чужое = "СамодельныйОбработчик"
    смешанный = {чужое: "// код", **перевёрнутый}
    имена = rules_index.handler_names("ПВД", смешанный)
    assert имена == ожидаемый + [чужое], (
        f"неизвестное имя потерялось или встало не в конец: {имена}"
    )

    # Неизвестный вид правила: порядка нет, но состав терять нельзя.
    имена = rules_index.handler_names("ПКС", смешанный)
    assert sorted(имена) == sorted(смешанный), (
        f"для неизвестного вида правила handler_names потерял имена: {имена}"
    )
    print(f"  handler_names: порядок проверен у {проверено} правил с обработчиками")


def проверка_handler_text(ix: Index) -> None:
    направление = ix.directions[НАПРАВЛЕНИЕ]
    пвд = [p for p in направление.pvd if p.code == ПРАВИЛО][0]

    # Число строк опорных обработчиков — то, на которое ссылается спецификация.
    for имя, ожидалось in (("ПередВыгрузкойОбъекта", 841), ("ПередОбработкойПравила", 1276)):
        настоящее, текст = rules_index.handler_text(пвд, "ПВД", имя)
        assert настоящее == имя, (
            f"handler_text({имя}) вернул имя {настоящее!r}"
        )
        assert текст == пвд.handlers[имя], (
            f"handler_text({имя}) вернул не тот текст: {len(текст)} знаков "
            f"против {len(пвд.handlers[имя])} в индексе"
        )
        строк = len(текст.splitlines())
        assert строк == ожидалось, (
            f"{ПРАВИЛО}/{имя}: строк {строк}, спецификация обещает {ожидалось}"
        )

    # Регистр имени не важен.
    for вариант in ("передвыгрузкойобъекта", "ПЕРЕДВЫГРУЗКОЙОБЪЕКТА", "ПеРеДвЫгРуЗкОйОбЪеКтА"):
        настоящее, текст = rules_index.handler_text(пвд, "ПВД", вариант)
        assert настоящее == "ПередВыгрузкойОбъекта", (
            f"имя {вариант!r} опознано как {настоящее!r} — регистр повлиял"
        )
        assert текст == пвд.handlers["ПередВыгрузкойОбъекта"], (
            f"имя {вариант!r} вернуло чужой текст"
        )

    # Несуществующее имя — LookupError с перечислением имеющихся, по порядку.
    сообщение = None
    try:
        rules_index.handler_text(пвд, "ПВД", "ПередЗагрузкойЧегоТоНесуществующего")
    except LookupError as ошибка:
        сообщение = str(ошибка)
    assert сообщение is not None, (
        f"у ПВД {ПРАВИЛО} нет такого обработчика, а handler_text не дал LookupError"
    )
    порядок = rules_index.handler_names("ПВД", пвд.handlers)
    позиции = []
    for имя in порядок:
        место = сообщение.find(имя)
        assert место >= 0, (
            f"в ошибке про несуществующий обработчик нет имени {имя!r}: {сообщение!r}"
        )
        позиции.append(место)
    assert позиции == sorted(позиции), (
        f"имена в ошибке перечислены не в порядке выполнения {порядок}: {сообщение!r}"
    )

    # По всему корпусу: имя и текст совпадают с индексом.
    проверено = len(все_обработчики(ix))
    for направление_ in ix.directions.values():
        for вид, правила in коллекции(направление_):
            for правило in правила:
                for имя, текст in правило.handlers.items():
                    настоящее, вернулось = rules_index.handler_text(правило, вид, имя.upper())
                    assert (настоящее, вернулось) == (имя, текст), (
                        f"{направление_.key}/{вид} {правило.code}: handler_text({имя.upper()!r}) "
                        f"вернул имя {настоящее!r} и {len(вернулось)} знаков, "
                        f"ожидалось {имя!r} и {len(текст)} знаков"
                    )
    print(f"  handler_text: сверено {проверено} обработчиков корпуса")


def проверка_matching_lines(ix: Index) -> None:
    текст = опорный_текст(ix)
    строки = текст.splitlines()

    # Игла приходит уже приведённой к нижнему регистру — так её подаёт поиск
    # (сравнение внутри идёт со строкой кода, приведённой к нижнему регистру).
    игла = "ВыгрузитьПоПравилу"
    ожидаемые = строки_с(текст, игла, закомментированные=False)
    assert len(ожидаемые) > 5, (
        f"в {ПРАВИЛО}/{ОБРАБОТЧИК} живых вхождений {игла} всего {len(ожидаемые)} — "
        "для проверки limit нужно больше"
    )

    найдено = rules_index.matching_lines(текст, игла.casefold(), limit=1000)
    номера = [n for n, _, _ in найдено]
    assert номера == ожидаемые, (
        f"matching_lines вернул строки {номера[:10]}, "
        f"а живые вхождения {игла} стоят на {ожидаемые[:10]}"
    )
    assert номера == sorted(номера), f"номера строк идут не по возрастанию: {номера[:10]}"

    for номер, фрагмент, обрезан in найдено:
        исходная = строки[номер - 1].strip()
        assert фрагмент == исходная[:200], (
            f"строка {номер}: фрагмент {фрагмент!r}, а в тексте {исходная[:200]!r}"
        )
        assert обрезан == (len(исходная) > 200), (
            f"строка {номер}: признак обрезки {обрезан}, а длина строки {len(исходная)} знаков"
        )
        assert not исходная.startswith("//"), (
            f"строка {номер} закомментирована, но попала в выдачу: {исходная[:60]!r}"
        )

    # limit соблюдается и режет с начала, а не откуда попало.
    for предел in (1, 2, 3):
        урезано = rules_index.matching_lines(текст, игла.casefold(), limit=предел)
        assert len(урезано) == предел, (
            f"limit = {предел}, вернулось {len(урезано)} строк"
        )
        assert [n for n, _, _ in урезано] == ожидаемые[:предел], (
            f"limit = {предел}: вернулись строки {[n for n, _, _ in урезано]}, "
            f"ожидались первые {ожидаемые[:предел]}"
        )

    # Закомментированная строка пропускается, настоящая находится.
    удаление = "РТиУ_ПеремещениеТоваров_Удаление"
    найдено = rules_index.matching_lines(текст, удаление.casefold(), limit=50)
    номера = [n for n, _, _ in найдено]
    assert номера == [СПЕЦ_СТРОКА_ЖИВОГО_ВЫЗОВА], (
        f"по {удаление} ожидалась только строка {СПЕЦ_СТРОКА_ЖИВОГО_ВЫЗОВА}, "
        f"вернулись {номера} (на {СПЕЦ_СТРОКА_КОММЕНТАРИЯ} вызов закомментирован)"
    )

    # Признак обрезки на строке длиннее 200 знаков.
    длинные = [
        номер for номер, строка in enumerate(строки, 1)
        if len(строка.strip()) > 200 and not строка.strip().startswith("//")
    ]
    assert длинные, (
        f"в {ПРАВИЛО}/{ОБРАБОТЧИК} нет живых строк длиннее 200 знаков — "
        "признак обрезки проверять не на чем"
    )
    номер = длинные[0]
    исходная = строки[номер - 1].strip()
    свой = rules_index.matching_lines(текст, исходная[:40].casefold(), limit=50)
    подходящие = [item for item in свой if item[0] == номер]
    assert подходящие, (
        f"строка {номер} не нашлась по собственному началу {исходная[:40]!r}"
    )
    _, фрагмент, обрезан = подходящие[0]
    assert обрезан is True, (
        f"строка {номер} длиной {len(исходная)} знаков не помечена обрезанной"
    )
    assert len(фрагмент) == 200, (
        f"строка {номер}: фрагмент длиной {len(фрагмент)} знаков, ожидалось 200"
    )

    # Пустой текст и отсутствие совпадений — пустой список, без исключений.
    assert rules_index.matching_lines("", "что угодно") == [], (
        "по пустому тексту matching_lines вернул не пустой список"
    )
    assert rules_index.matching_lines(текст, "такойстрокинетвкоде20260918") == [], (
        "по несуществующей игле matching_lines вернул не пустой список"
    )
    print(f"  matching_lines: {len(ожидаемые)} живых вхождений {игла}, обрезка и limit в порядке")


