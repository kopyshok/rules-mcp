    виды = [h["вид правила"] for h in попадания]
    assert set(виды) == set(порядок), (
        f"для проверки порядка нужен запрос, попадающий во все виды {порядок}; "
        f"вернулись только {sorted(set(виды))}"
    )
    места = [порядок.index(в) for в in виды]
    assert места == sorted(места), (
        f"виды правил в выдаче идут не в порядке {порядок}: "
        f"первое нарушение на позиции "
        f"{next(i for i in range(1, len(места)) if места[i] < места[i - 1])}, "
        f"вокруг {виды[max(0, next(i for i in range(1, len(места)) if места[i] < места[i - 1]) - 2):][:5]}"
    )

    # Порядок направлений — тот, в каком они переданы в targets.
    цели = list(ix.directions.values())
    много = ix.search(цели, ШИРОКИЙ_ЗАПРОС, limit=10_000, lines_per_handler=1)
    встречены: list[str] = []
    for h in много:
        if not встречены or встречены[-1] != h["направление"]:
            assert h["направление"] not in встречены, (
                f"направление {h['направление']} встречается в выдаче не одним куском: "
                f"порядок {встречены + [h['направление']]}"
            )
            встречены.append(h["направление"])
    ожидались = [d.key for d in цели if d.key in встречены]
    assert встречены == ожидались, (
        f"направления в выдаче идут как {встречены}, а в targets переданы как {ожидались}"
    )

    # Неизвестный вид правила — LookupError с перечислением допустимых (1.5).
    сообщение = None
    try:
        пусто = ix.search([направление], ШИРОКИЙ_ЗАПРОС, kind="ПКС")
    except LookupError as ошибка:
        сообщение = str(ошибка)
    assert сообщение is not None, (
        f"search с kind='ПКС' вернул {len(пусто)} попаданий вместо LookupError — "
        "опечатка в фильтре не должна выглядеть как «ничего не нашлось» (1.5)"
    )
    for вид in rules_index.RULE_KINDS:
        assert вид in сообщение, (
            f"ошибка про неизвестный вид правила не перечисляет {вид}: {сообщение!r}"
        )
    print(f"  search: порядок обхода {порядок}, направления в порядке targets, "
          f"неизвестный вид даёт ошибку")


