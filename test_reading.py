def проверка_откуда_процессы(ix: Index) -> None:
    веток = пришлых = 0
    for направление in ix.directions.values():
        for пвд in направление.pvd:
            где = f"{направление.key}/{пвд.code}"
            откуда = ix.pvd_block_sources(направление, пвд)
            assert откуда["свои"] == sorted(пвд.blocks), f"{где}: свои {откуда['свои']}, в ветке {пвд.blocks}"
            # Ожидание из данных: метки каждого включённого вызываемого ПКО.
            ожидалось: dict[str, set[str]] = {}
            for имя in пвд.pko_calls:
                пко = направление.pko.get(имя)
                if пко is not None and not пко.disabled:
                    for метка in пко.blocks:
                        ожидалось.setdefault(метка, set()).add(имя)
            получено = {м: set(и) for м, и in откуда["от вызываемых правил"].items()}
            assert получено == ожидалось, f"{где}: пришедшие метки {получено}, ожидалось {ожидалось}"
            объединение = sorted(set(откуда["свои"]) | set(откуда["от вызываемых правил"]))
            assert объединение == ix.pvd_blocks(направление, пвд), (
                f"{где}: свои и пришедшие {объединение} не равны процессам {ix.pvd_blocks(направление, пвд)}"
            )
            веток += 1
            пришлых += len(set(откуда["от вызываемых правил"]) - set(откуда["свои"]))

    # Эталон: ВГОКомиссия у РеализацияТоваровУслуг чужая — своя ветка закомментирована.
    направление = ix.directions[НАПРАВЛЕНИЕ]
    пвд = [p for p in направление.pvd if p.code == ПРАВИЛО][0]
    источник = "РеализацияТоваровУслуг_ПередачаТоваровХранителю"
    assert "ВГОКомиссия" not in пвд.blocks and "ВГОКомиссия" in направление.pko[источник].blocks, (
        "данные сменились: ВГОКомиссия уже своя у ветки или не помечает правило хранителя"
    )
    assert 493 in строки_с(опорный_текст(ix), "ВГОКомиссия", закомментированные=True), (
        "закомментированной ветки ВГОКомиссия на строке 493 больше нет"
    )
    откуда = ix.pvd_block_sources(направление, пвд)
    assert "ВГОКомиссия" not in откуда["свои"], f"ВГОКомиссия числится своей: {откуда}"
    assert источник in откуда["от вызываемых правил"].get("ВГОКомиссия", []), (
        f"ВГОКомиссия не приписана {источник}: {откуда}"
    )
    print(f"  откуда процессы: {веток} веток, пришедших только от правил меток {пришлых}")


