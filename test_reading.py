# 2.1.0, пункт 3: отбор поиска по имени правила


def проверка_search_отбор_по_имени_правила(ix: Index) -> None:
    направление = ix.directions[НАПРАВЛЕНИЕ]
    запрос = "Объект"
    БОЛЬШОЙ = 10**6

    def искать(**фильтры) -> list[dict]:
        return ix.search([направление], запрос, limit=БОЛЬШОЙ, lines_per_handler=БОЛЬШОЙ, **фильтры)

    # Правило регистрации по имени объекта = то же, что по его кодам.
    по_объектам = _про_по_объектам(направление)
    непустых = многозначных = 0
    for имя, правила in sorted(по_объектам.items()):
        объект = obj_short(правила[0].obj)
        по_кодам = {_ключ(h) for p in правила for h in искать(kind="ПРО", rule=p.code)}
        по_имени = искать(kind="ПРО", rule=объект)
        assert {_ключ(h) for h in по_имени} == по_кодам, (
            f"ПРО по объекту {объект}: {len(по_имени)} попаданий, по кодам "
            f"{[p.code for p in правила]} — {len(по_кодам)}"
        )
        assert {h["правило"] for h in по_имени} <= {p.code for p in правила}, объект
        if по_кодам:
            непустых += 1
            многозначных += len(правила) > 1 and len({h["правило"] for h in по_имени}) > 1
    assert непустых and многозначных, (
        f"нечего проверять: объектов с попаданиями {непустых}, "
        f"многозначных с попаданиями из разных правил {многозначных}"
    )

    # Наименование тоже годится, регистр не важен.
    наименование = "Реализация товаров и услуг (многокол)"
    про = [p for p in направление.pro if p.name == наименование]
    assert len(про) == 1, f"ожидалось одно ПРО «{наименование}», в данных {len(про)}"
    по_коду = {_ключ(h) for h in искать(rule=про[0].code, kind="ПРО")}
    assert по_коду and {_ключ(h) for h in искать(rule=наименование.upper())} == по_коду, (
        f"ПРО по наименованию «{наименование}» дало не то же, что по коду {про[0].code}"
    )

    # Разрешение по каждому направлению отдельно: где правила нет, оно не мешает.
    цели = list(ix.directions.values())
    где_есть = {
        d.key for d in цели if any(p.name.casefold() == наименование.casefold() for p in d.pro)
    }
    assert где_есть == {НАПРАВЛЕНИЕ}, f"ПРО «{наименование}» есть в {где_есть} — нужен другой пример"
    везде = ix.search(цели, запрос, rule=наименование, limit=БОЛЬШОЙ, lines_per_handler=БОЛЬШОЙ)
    assert везде and {h["направление"] for h in везде} == где_есть, (
        f"по всем направлениям отбор «{наименование}» дал направления "
        f"{sorted({h['направление'] for h in везде})}, ожидалось {sorted(где_есть)}"
    )

    # Опечатка — ошибка с похожими, а не пустая выдача.
    сообщение = _ошибка(lambda: ix.search(цели, запрос, rule="РеализацияТоваровУслу"))
    assert сообщение and "Похожие" in сообщение and ПРАВИЛО in сообщение, (
        f"опечатка в отборе rule не дала ошибки с похожими: {сообщение!r}"
    )
    # Правило есть, но другого вида — тоже ошибка, а не пустота.
    сообщение = _ошибка(lambda: ix.search([направление], запрос, kind="Запрос", rule=ПРАВИЛО))
    assert сообщение, f"ПВД {ПРАВИЛО} в отборе с видом «Запрос» дал пустую выдачу вместо ошибки"
    print(f"  отбор rule по объекту: {len(по_объектам)} объектов ПРО, с попаданиями {непустых}, "
          f"из них многозначных {многозначных}; опечатка даёт ошибку")


