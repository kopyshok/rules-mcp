def _коды_по_видам(направление: Direction) -> dict[str, set[str]]:
    return {вид: {r.code.casefold() for r in правила} for вид, правила in коллекции(направление)}


def _про_по_объектам(направление: Direction) -> dict[str, list]:
    """Короткое имя объекта → правила регистрации, к нему относящиеся."""
    out: dict[str, list] = {}
    for правило in направление.pro:
        out.setdefault(obj_short(правило.obj).casefold(), []).append(правило)
    return out


def проверка_find_rule(ix: Index) -> None:
    направление = ix.directions[НАПРАВЛЕНИЕ]
    коды = _коды_по_видам(направление)

    # По одному коду каждого вида, который есть только у этого вида.
    for вид in rules_index.RULE_KINDS:
        чужие = set().union(*(v for k, v in коды.items() if k != вид))
        уникальные = sorted(коды[вид] - чужие)
        assert уникальные, (
            f"в {НАПРАВЛЕНИЕ} нет ни одного кода {вид}, не пересекающегося с другими видами — "
            "проверить однозначный поиск не на чем"
        )
        код = уникальные[0]
        найденный_вид, правило = ix.find_rule(направление, код)
        assert найденный_вид == вид, (
            f"код {код} принадлежит {вид}, а find_rule вернул вид {найденный_вид!r}"
        )
        assert правило.code.casefold() == код, (
            f"по коду {код} вернулось правило с кодом {правило.code!r}"
        )
        assert найденный_вид in rules_index.RULE_KINDS, (
            f"вид правила {найденный_вид!r} вне RULE_KINDS = {rules_index.RULE_KINDS}"
        )

        # Регистр кода не важен (1.5).
        for вариант in (правило.code.upper(), правило.code.lower()):
            вид_2, правило_2 = ix.find_rule(направление, вариант)
            assert (вид_2, правило_2.code) == (найденный_вид, правило.code), (
                f"код {вариант!r} нашёл {вид_2} {правило_2.code!r}, "
                f"а {правило.code!r} — {найденный_вид} {правило.code!r}: регистр повлиял"
            )

    # Несуществующий код — LookupError с внятным текстом.
    небывалый = "ТакогоПравилаНетИНеБудет_20260918"
    assert небывалый.casefold() not in set().union(*коды.values()), (
        f"код-пустышка {небывалый} внезапно есть в данных, тест надо переписать"
    )
    сообщение = None
    try:
        ix.find_rule(направление, небывалый)
    except LookupError as ошибка:
        сообщение = str(ошибка)
    assert сообщение is not None, (
        f"поиск несуществующего правила {небывалый} прошёл без LookupError"
    )
    assert len(сообщение) > 10, (
        f"на несуществующий код LookupError сказал только {сообщение!r} — "
        "по 1.5 требуются похожие коды"
    )

    # Коллизия кодов между видами. По данным на 2026-09-18 в УПП_ERP таких 25
    # (все — пара ПВД/ПКО), поэтому ветка «коллизий нет» здесь не срабатывает.
    столкнувшиеся = sorted(
        (код, sorted(вид for вид, набор in коды.items() if код in набор))
        for код in set().union(*коды.values())
        if sum(код in набор for набор in коды.values()) > 1
    )
    if not столкнувшиеся:
        print(f"  find_rule: в {НАПРАВЛЕНИЕ} коллизий кодов между видами нет — ветка не проверяется")
    else:
        код, виды = столкнувшиеся[0]
        сообщение = None
        try:
            ix.find_rule(направление, код)
        except LookupError as ошибка:
            сообщение = str(ошибка)
        assert сообщение is not None, (
            f"код {код} есть сразу у {виды}, но find_rule без kind не дал LookupError (1.5)"
        )
        for вид in виды:
            assert вид in сообщение, (
                f"код {код} есть у {виды}, а ошибка не называет {вид}: {сообщение!r}"
            )
        # С указанным видом неоднозначности нет.
        for вид in виды:
            найденный_вид, правило = ix.find_rule(направление, код, вид)
            assert найденный_вид == вид, (
                f"find_rule(код={код}, kind={вид}) вернул вид {найденный_вид!r}"
            )
            assert правило.code.casefold() == код, (
                f"find_rule(код={код}, kind={вид}) вернул правило {правило.code!r}"
            )
        print(f"  find_rule: коллизий кодов в {НАПРАВЛЕНИЕ} — {len(столкнувшиеся)}, проверен {код} ({виды})")

    # Неизвестный вид правила — ошибка, а не молчаливый пустой поиск (1.5).
    сообщение = None
    try:
        ix.find_rule(направление, ПРАВИЛО, "ПКС")
    except LookupError as ошибка:
        сообщение = str(ошибка)
    assert сообщение is not None, (
        "find_rule с видом правила «ПКС» прошёл без LookupError — "
        "опечатка в фильтре не должна выглядеть как «не найдено» (1.5)"
    )
    for вид in rules_index.RULE_KINDS:
        assert вид in сообщение, (
            f"ошибка про неизвестный вид правила не перечисляет {вид}: {сообщение!r}"
        )


def проверка_find_rule_по_наименованию_и_объекту(ix: Index) -> None:
    """Правила регистрации адресуются не кодом: коды у них числовые."""
    направление = ix.directions[НАПРАВЛЕНИЕ]

    числовых = [p.code for p in направление.pro if p.code.isdigit()]
    assert len(числовых) == len(направление.pro), (
        f"в {НАПРАВЛЕНИЕ} не все коды ПРО числовые: "
        f"{[p.code for p in направление.pro if not p.code.isdigit()][:5]}"
    )

    по_объектам = _про_по_объектам(направление)

    # Поиск по короткому имени объекта, когда правило регистрации одно.
    объект = "ПеремещениеТоваров"
    подходящие = по_объектам.get(объект.casefold(), [])
    assert len(подходящие) == 1, (
        f"ожидалось одно ПРО по объекту {объект}, в данных {len(подходящие)}: "
        f"{[(p.code, p.name) for p in подходящие]}"
    )
    вид, правило = ix.find_rule(направление, объект, "ПРО")
    assert вид == "ПРО", f"по объекту {объект} вернулся вид {вид!r}, ожидался ПРО"
    assert правило.code == подходящие[0].code, (
        f"по объекту {объект} вернулось ПРО {правило.code!r} «{правило.name}», "
        f"а в данных {подходящие[0].code!r} «{подходящие[0].name}»"
    )

    # Поиск по наименованию — так различаются два ПРО одного объекта.
    наименование = "Реализация товаров и услуг (многокол)"
    по_имени = [p for p in направление.pro if p.name.casefold() == наименование.casefold()]
    assert len(по_имени) == 1, (
        f"ожидалось одно ПРО с наименованием «{наименование}», в данных "
        f"{[(p.code, p.name) for p in по_имени]}"
    )
    вид, правило = ix.find_rule(направление, наименование, "ПРО")
    assert (вид, правило.code) == ("ПРО", по_имени[0].code), (
        f"по наименованию «{наименование}» вернулось {вид} {правило.code!r}, "
        f"ожидалось ПРО {по_имени[0].code!r}"
    )
    # Регистр наименования не важен.
    вид_2, правило_2 = ix.find_rule(направление, наименование.upper(), "ПРО")
    assert (вид_2, правило_2.code) == (вид, правило.code), (
        f"наименование в верхнем регистре нашло {вид_2} {правило_2.code!r}, "
        f"а в исходном — {вид} {правило.code!r}: регистр повлиял"
    )

    # Многозначность — ошибка, а не молчаливый выбор первого попавшегося.
    многозначные = {имя: правила for имя, правила in по_объектам.items() if len(правила) > 1}
    assert многозначные, (
        f"в {НАПРАВЛЕНИЕ} нет объектов с несколькими ПРО — многозначность проверять не на чем"
    )
    for имя, правила in sorted(многозначные.items()):
        запрос = obj_short(правила[0].obj)
        сообщение = None
        try:
            вид, найдено = ix.find_rule(направление, запрос, "ПРО")
        except LookupError as ошибка:
            сообщение = str(ошибка)
        assert сообщение is not None, (
            f"у объекта {запрос} правил регистрации {len(правила)} "
            f"({[p.code for p in правила]}), а find_rule молча выбрал "
            f"{вид} {найдено.code!r} «{найдено.name}» (1.5)"
        )
        for кандидат in правила:
            assert кандидат.code in сообщение, (
                f"ошибка про многозначность объекта {запрос} не называет кандидата "
                f"{кандидат.code} «{кандидат.name}»: {сообщение!r}"
            )

    # Приоритет признаков: точный код бьёт совпадение по имени объекта.
    спорный = "Покупатели"
    свои_коды = [p for p in направление.pvd if p.code.casefold() == спорный.casefold()]
    по_объекту = [p for p in направление.pvd if obj_short(p.obj).casefold() == спорный.casefold()]
    assert len(свои_коды) == 1 and len(по_объекту) > 1, (
        f"для проверки приоритета нужен один ПВД с кодом {спорный} и несколько с таким "
        f"объектом; в данных кодов {[p.code for p in свои_коды]}, "
        f"объектов {[p.code for p in по_объекту]}"
    )
    вид, правило = ix.find_rule(направление, спорный)
    assert (вид, правило.code) == ("ПВД", свои_коды[0].code), (
        f"запрос {спорный} обязан однозначно давать ПВД с кодом {свои_коды[0].code!r} "
        f"(код важнее имени объекта), а вернулось {вид} {правило.code!r}"
    )

    print(
        f"  find_rule: ПРО по объекту и наименованию находятся, объектов с несколькими "
        f"ПРО — {len(многозначные)}, все дают ошибку"
    )


