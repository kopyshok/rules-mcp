# 2.1.0, пункт 1: строки вызовов правил конвертации в trace_document

# Вызов ПКО одной строкой. Многострочных вызовов в корпусе нет (проверено при
# написании), поэтому построчное выражение годится как независимое ожидание.
_ВЫЗОВ_В_СТРОКЕ = re.compile(r'(?:ВыгрузитьПоПравилу\s*\([^()"]*|ИмяПКО\s*=\s*)"([^"]+)"')


def _живая(текст: str, номер: int) -> str:
    строка = текст.splitlines()[номер - 1]
    assert not строка.strip().startswith("//"), f"строка {номер} закомментирована: {строка.strip()[:80]!r}"
    return строка


def проверка_строки_вызовов_правил(ix: Index) -> None:
    пустых = []
    мест = 0
    for направление in ix.directions.values():
        for пвд in направление.pvd:
            for имя in пвд.pko_calls:
                поля = rules_index.branch_call_places(пвд, имя)
                места = поля["где вызывается"]
                где = f"{направление.key}/{пвд.code} → {имя}"
                if isinstance(места, str):
                    if имя != пвд.conv_rule:
                        пустых.append(где)
                    continue
                assert места, f"{где}: пустой список мест вместо слов"
                assert поля.get("задано и в свойствах ветки", False) == (имя == пвд.conv_rule), (
                    f"{где}: пометка о свойствах ветки {поля.get('задано и в свойствах ветки')}, "
                    f"правило ветки в свойствах — {пвд.conv_rule!r}"
                )
                for место in места:
                    строка = _живая(пвд.handlers[место["обработчик"]], место["строка"])
                    assert имя in _ВЫЗОВ_В_СТРОКЕ.findall(строка), (
                        f"{где}: {место} указывает на строку без вызова: {строка.strip()[:120]!r}"
                    )
                    мест += 1
            # Полнота: каждый живой вызов из текста ветки попал в места.
            for обработчик, текст in пвд.handlers.items():
                for номер, строка in enumerate(текст.splitlines(), 1):
                    if строка.strip().startswith("//"):
                        continue
                    for имя in _ВЫЗОВ_В_СТРОКЕ.findall(строка):
                        места = rules_index.branch_call_places(пвд, имя)["где вызывается"]
                        assert isinstance(места, list) and {"обработчик": обработчик, "строка": номер} in места, (
                            f"{направление.key}/{пвд.code}: вызов {имя} на строке {номер} "
                            f"{обработчик} не показан; показано {места}"
                        )
    assert not пустых, f"правил без места вызова и не из свойств ветки {len(пустых)}: {пустых[:5]}"

    # Эталонная ветка: номера из данных, а не зашитые вслепую.
    пвд = [p for p in ix.directions[НАПРАВЛЕНИЕ].pvd if p.code == ПРАВИЛО][0]
    текст = пвд.handlers[ОБРАБОТЧИК]
    for имя, спец in (
        ("РеализацияТоваровУслуг_ПеремещениеТоваров", 430),
        ("ПеремещениеТоваровММ_ПеремещениеТоваров", 448),
        ("РТиУ_ВнПотребление", 523),
        ("РТиУ_ПеремещениеТоваров_Удаление", СПЕЦ_СТРОКА_ЖИВОГО_ВЫЗОВА),
    ):
        по_данным = строки_с(текст, f'"{имя}"', закомментированные=False)
        assert по_данным == [спец], f"{имя}: в живом коде строки {по_данным}, спецификация обещает {спец}"
        места = rules_index.branch_call_places(пвд, имя)["где вызывается"]
        assert места == [{"обработчик": ОБРАБОТЧИК, "строка": спец}], f"{имя}: места {места}"
    assert СПЕЦ_СТРОКА_КОММЕНТАРИЯ in строки_с(
        текст, '"РТиУ_ПеремещениеТоваров_Удаление"', закомментированные=True
    ), "закомментированный вызов на строке 812 пропал из данных — проверять нечего"

    # Вызовы через общие алгоритмы: те же пары «алгоритм — правило», что у
    # algorithms_used, и обе строки цепочки указывают на живой вызов.
    цепочек = 0
    for направление in ix.directions.values():
        for пвд in направление.pvd:
            через = ix.algorithms_used(направление, "\n".join(пвд.handlers.values()))
            места = ix.algorithm_call_places(направление, пвд, "ПВД")
            ожидалось = {(алг, имя) for алг, имена in через.items() for имя in имена}
            получено = {(м["вызов в алгоритме"]["алгоритм"], м["правило конвертации"]) for м in места}
            assert получено == ожидалось, (
                f"{направление.key}/{пвд.code}: лишние {sorted(получено - ожидалось)[:3]}, "
                f"потерянные {sorted(ожидалось - получено)[:3]}"
            )
            for м in места:
                внутри, снаружи = м["вызов в алгоритме"], м["правило зовёт алгоритм"]
                алг_текст = направление.algorithms[внутри["алгоритм"]].handlers["Текст"]
                assert внутри["строки"], f"{направление.key}/{пвд.code}: {м} без строки в алгоритме"
                for номер in внутри["строки"]:
                    assert м["правило конвертации"] in _ВЫЗОВ_В_СТРОКЕ.findall(_живая(алг_текст, номер)), м
                for номер in снаружи["строки"]:
                    строка = _живая(пвд.handlers[снаружи["обработчик"]], номер)
                    assert f"Алгоритмы.{снаружи['алгоритм']}" in строка, (м, строка.strip()[:120])
                цепочек += 1
    assert цепочек, "ни одной цепочки через общие алгоритмы — проверять нечего"
    print(f"  строки вызовов: {мест} мест прямых вызовов, {цепочек} цепочек через алгоритмы; "
          f"без места — {len(пустых)}")


